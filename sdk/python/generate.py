"""Generate pinned option and result models; private HTTP lives outside generated code."""
import json, os, pathlib, re, shutil, subprocess, sys, tempfile
root=pathlib.Path(__file__).resolve().parents[2]
version=re.search(r'^version = "([^"]+)"', (root/'Cargo.toml').read_text(),re.M).group(1)
mode=sys.argv[1] if len(sys.argv)>1 else 'check'
target=root/'sdk/python/src/cubepals_pryx/generated'
with tempfile.TemporaryDirectory(prefix='pryx-python-') as tmp:
    temporary=pathlib.Path(tmp)
    config=temporary/'config.json'
    config.write_text(json.dumps({'project_name_override':'cubepals-pryx','package_name_override':'cubepals_pryx_generated','package_version_override':version}))
    output=temporary/'cubepals_pryx_generated'
    document=json.loads((root/'control/openapi/pryx.openapi.json').read_text())
    schemas=document['components']['schemas']
    needed=set()
    def include(name):
        if name in needed:return
        needed.add(name)
        def refs(value):
            if isinstance(value,dict):
                for key,child in value.items():
                    if key=='$ref' and child.startswith('#/components/schemas/'):include(child.rsplit('/',1)[1])
                    else:refs(child)
            elif isinstance(value,list):
                for child in value:refs(child)
        refs(schemas[name])
    for name in ('MakeRequest','Sandbox','Snapshot','AgentResult'):include(name)
    document['paths']={}
    document['components']['schemas']={name:schema for name,schema in schemas.items() if name in needed}
    spec=temporary/'models.openapi.json'
    spec.write_text(json.dumps(document))
    subprocess.run(['openapi-python-client','generate','--path',str(spec),'--config',str(config),'--output-path',str(output),'--meta','none'],check=True)
    shutil.rmtree(output/'api',ignore_errors=True)
    (output/'client.py').unlink()
    (output/'__init__.py').write_text('\"\"\"Generated wire models, without an HTTP client.\"\"\"\n')
    for file in output.rglob('*.py'):
        source=file.read_text()
        # REUSE-IgnoreStart
        file.write_text('# SPDX-License-Identifier: FSL-1.1-ALv2\n# Generated by sdk/python/generate.py.\n'+source)
        # REUSE-IgnoreEnd
    wanted={str(f.relative_to(output)):f.read_bytes() for f in output.rglob('*.py')}
    # REUSE-IgnoreStart
    defaults=('# SPDX-License-Identifier: FSL-1.1-ALv2\n# Generated by sdk/python/generate.py.\nSDK_DEFAULTS = '+repr(json.loads((root/'control/openapi/pryx.openapi.json').read_text())['x-pryx-sdk'])+'\n').encode()
    # REUSE-IgnoreEnd
    wanted['defaults.py']=defaults
    (output/'defaults.py').write_bytes(defaults)
    if mode=='generate':
        if target.exists(): shutil.rmtree(target)
        shutil.copytree(output,target,ignore=shutil.ignore_patterns('.ruff_cache','__pycache__'))
    elif mode=='check':
        actual={str(f.relative_to(target)):f.read_bytes() for f in target.rglob('*.py')}
        if actual!=wanted:sys.exit('Python API generation drift')
    else:sys.exit('generate.py generate|check')
