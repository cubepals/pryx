"""Generate pinned Python models/HTTP methods; NDJSON is implemented in the small public wrapper."""
import json, os, pathlib, re, shutil, subprocess, sys, tempfile
root=pathlib.Path(__file__).resolve().parents[2]
version=re.search(r'^version = "([^"]+)"', (root/'Cargo.toml').read_text(),re.M).group(1)
mode=sys.argv[1] if len(sys.argv)>1 else 'check'
target=root/'sdk/python/src/cubepals_pryx/generated'
with tempfile.TemporaryDirectory(prefix='pryx-python-') as tmp:
    temporary=pathlib.Path(tmp)
    config=temporary/'config.json'
    config.write_text(json.dumps({'project_name_override':'cubepals-pryx','package_name_override':'cubepals_pryx_generated','package_version_override':version}))
    output=temporary/'cubepals_pryx_generated'
    subprocess.run(['openapi-python-client','generate','--path',str(root/'control/openapi/pryx.openapi.json'),'--config',str(config),'--output-path',str(output),'--meta','none'],check=True)
    for file in output.rglob('*.py'):
        source=file.read_text()
        if file.name=='client.py':
            source=source.replace('token: str\n','token: str = field(repr=False)\n')
            source=source.replace('alias="headers")','alias="headers", repr=False)').replace('alias="cookies")','alias="cookies", repr=False)').replace('alias="httpx_args")','alias="httpx_args", repr=False)')
        # REUSE-IgnoreStart
        file.write_text('# SPDX-License-Identifier: FSL-1.1-ALv2\n# Generated by sdk/python/generate.py.\n'+source)
        # REUSE-IgnoreEnd
    wanted={str(f.relative_to(output)):f.read_bytes() for f in output.rglob('*.py')}
    if mode=='generate':
        if target.exists(): shutil.rmtree(target)
        shutil.copytree(output,target,ignore=shutil.ignore_patterns('.ruff_cache','__pycache__'))
    elif mode=='check':
        actual={str(f.relative_to(target)):f.read_bytes() for f in target.rglob('*.py')}
        if actual!=wanted:sys.exit('Python API generation drift')
    else:sys.exit('generate.py generate|check')
