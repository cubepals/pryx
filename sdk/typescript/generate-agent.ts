/** Generate SDK-only agent types and kernel defaults from the Rust-owned agent document.
 * The public control and node documents remain independent of new sandbox-local families. */
import { readFileSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'

const mode = process.argv[2]
if (!['generate', 'check'].includes(mode ?? '')) throw new Error('generate-agent.ts generate | check')
const spec = JSON.parse(readFileSync(new URL('../../agent/openapi.json', import.meta.url), 'utf8'))
const licenceTag = 'SPDX-' + 'License-Identifier'
const header = `// ${licenceTag}: FSL-1.1-ALv2\n// Generated by sdk/typescript/generate-agent.ts.\n`
const targets = [
  [
    new URL('./src/generated/tools.ts', import.meta.url),
    `${header}export const TOOL_DEFAULTS = ${JSON.stringify(spec['x-pryx-tools'])} as const\n`,
  ],
  [
    new URL('../python/src/cubepals_pryx/generated/tools.py', import.meta.url),
    `# ${licenceTag}: FSL-1.1-ALv2\n# Generated by sdk/typescript/generate-agent.ts.\nTOOL_DEFAULTS = ${JSON.stringify(spec['x-pryx-tools'])}\n`,
  ],
  [new URL('./src/generated/agent.ts', import.meta.url), header + astToString(await openapiTS(spec))],
  [
    new URL('./src/generated/kernels.ts', import.meta.url),
    `${header}export const KERNEL_DEFAULTS = ${JSON.stringify(spec['x-pryx-kernels'])} as const\n`,
  ],
  [
    new URL('../python/src/cubepals_pryx/generated/kernels.py', import.meta.url),
    `# ${licenceTag}: FSL-1.1-ALv2\n# Generated by sdk/typescript/generate-agent.ts.\nKERNEL_DEFAULTS = ${JSON.stringify(spec['x-pryx-kernels'])}\n`,
  ],
] as const
if (!spec['x-pryx-kernels']) throw new Error('Missing Rust-owned kernel defaults')
for (const [path, value] of targets) {
  if (mode === 'generate') writeFileSync(path, value)
  else if (readFileSync(path, 'utf8') !== value) throw new Error(`Agent SDK drift: ${path.pathname}`)
}
console.log(`Agent SDK types and defaults: ${mode}`)
