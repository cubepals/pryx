/** Generate node API types from this repository's Rust schemas and fail on committed drift. */

import { createHash } from 'node:crypto'

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'

import { edgeContract } from '../src/edge-contract.ts'
import { publicContract } from '../src/public-contract.ts'
import { SDK_DEFAULTS } from '../src/sdk-defaults.ts'

const mode = process.argv[2]
if (mode !== 'generate' && mode !== 'check') throw new Error('usage: openapi.ts generate | check')
for (const direction of ['reads', 'writes']) {
  const source = new URL(`../../openapi/node-${direction}.openapi.json`, import.meta.url)
  const target = new URL(`../src/generated/node-${direction}.ts`, import.meta.url)
  const spec = readFileSync(source, 'utf8')
  // REUSE-IgnoreStart
  const generated = [
    '// SPDX-FileCopyrightText: 2026 The Cubepals Authors',
    '// SPDX-License-Identifier: FSL-1.1-ALv2',
    `// Generated from openapi/node-${direction}.openapi.json; sha256 ${createHash('sha256').update(spec).digest('hex')}.`,
    astToString(
      await openapiTS(JSON.parse(spec), {
        defaultNonNullable: direction === 'writes',
      }),
    ),
  ].join('\n')
  // REUSE-IgnoreEnd
  if (mode === 'generate') writeFileSync(target, generated)
  else if (readFileSync(target, 'utf8') !== generated) throw new Error(`API type drift: ${target.pathname}`)
}
console.log(`Node API types: ${mode}`)

const publicSpec = `${JSON.stringify(publicContract(), null, 2)}\n`
const publicPath = new URL('../openapi/pryx.openapi.json', import.meta.url)
const sdkPath = new URL('../../sdk/typescript/src/generated/api.ts', import.meta.url)
mkdirSync(new URL('../openapi/', import.meta.url), { recursive: true })
mkdirSync(new URL('../../sdk/typescript/src/generated/', import.meta.url), { recursive: true })
// REUSE-IgnoreStart
const publicTypes =
  '// SPDX-License-Identifier: FSL-1.1-ALv2\n// Generated by control/tools/openapi.ts.\n' +
  astToString(await openapiTS(JSON.parse(publicSpec), { defaultNonNullable: false }))
// REUSE-IgnoreEnd
for (const [path, value] of [
  [publicPath, publicSpec],
  [sdkPath, publicTypes],
] as const) {
  if (mode === 'generate') writeFileSync(path, value)
  else if (readFileSync(path, 'utf8') !== value) throw new Error(`Public API drift: ${path.pathname}`)
}
console.log(`Public API and SDK types: ${mode}`)
// REUSE-IgnoreStart
const sdkDefaults =
  '// SPDX-License-Identifier: FSL-1.1-ALv2\n// Generated by control/tools/openapi.ts.\nexport const SDK_DEFAULTS = ' +
  JSON.stringify(SDK_DEFAULTS) +
  ' as const\n'
// REUSE-IgnoreEnd
const defaultsPath = new URL('../../sdk/typescript/src/generated/defaults.ts', import.meta.url)
if (mode === 'generate') writeFileSync(defaultsPath, sdkDefaults)
else if (readFileSync(defaultsPath, 'utf8') !== sdkDefaults) throw new Error('SDK defaults drift')

const edgeSpec = `${JSON.stringify(edgeContract(), null, 2)}\n`
const edgePath = new URL('../openapi/edge.openapi.json', import.meta.url)
const edgeTypesPath = new URL('../../edge/src/generated/api.ts', import.meta.url)
mkdirSync(new URL('../../edge/src/generated/', import.meta.url), { recursive: true })
// REUSE-IgnoreStart
const edgeTypes =
  '// SPDX-License-Identifier: FSL-1.1-ALv2\n// Generated by control/tools/openapi.ts.\n' +
  astToString(await openapiTS(JSON.parse(edgeSpec), { defaultNonNullable: false }))
// REUSE-IgnoreEnd
for (const [path, value] of [
  [edgePath, edgeSpec],
  [edgeTypesPath, edgeTypes],
] as const) {
  if (mode === 'generate') writeFileSync(path, value)
  else if (readFileSync(path, 'utf8') !== value) throw new Error(`Edge API drift: ${path.pathname}`)
}
console.log(`Edge API types: ${mode}`)

for (const name of ['hetzner', 'boat']) {
  const source = new URL(`../src/providers/openapi/${name}.openapi.json`, import.meta.url)
  const target = new URL(`../src/providers/generated/${name}.ts`, import.meta.url)
  mkdirSync(new URL('../src/providers/generated/', import.meta.url), { recursive: true })
  // REUSE-IgnoreStart
  const generated =
    '// SPDX-License-Identifier: FSL-1.1-ALv2\n// Generated from the pinned provider contract.\n' +
    astToString(await openapiTS(JSON.parse(readFileSync(source, 'utf8')), { defaultNonNullable: false }))
  // REUSE-IgnoreEnd
  if (mode === 'generate') writeFileSync(target, generated)
  else if (readFileSync(target, 'utf8') !== generated) throw new Error(`Provider type drift: ${name}`)
}
console.log(`Provider API types: ${mode}`)

const proxySource = readFileSync(new URL('../../sdk/git-proxy.js', import.meta.url), 'utf8')
  .split('\n')
  .slice(1)
  .join('\n')
const proxyTarget = new URL('../../sdk/typescript/src/generated/git-proxy.ts', import.meta.url)
// REUSE-IgnoreStart
const proxyGenerated =
  '// SPDX-License-Identifier: FSL-1.1-ALv2\n// Generated by control/tools/openapi.ts.\nexport const GIT_PROXY_SOURCE = ' +
  JSON.stringify(proxySource) +
  ' as const\n'
// REUSE-IgnoreEnd
if (mode === 'generate') writeFileSync(proxyTarget, proxyGenerated)
else if (readFileSync(proxyTarget, 'utf8') !== proxyGenerated)
  throw new Error('Git HTTP bridge generation drift')
